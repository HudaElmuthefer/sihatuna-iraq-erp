// ── إصلاح فجوة أمنية بنظام المنشآت المتعددة ──────────────────────────────────
// النظام يدعم نوعين من حسابات "admin": إدمن عام على مستوى الوزارة (بدون
// hospitalId — يشوف ويدير كل شيء بكل المنشآت)، وإدمن محلي مرتبط بمنشأة
// واحدة تحديداً (hospitalId محدَّد بحسابه). كان middleware/requireAdmin.js
// يتحقق فقط من role === 'admin' بغض النظر عن hospitalId — يعني إدمن محلي
// لمستشفى معيّن كان يقدر (عبر استدعاء API مباشر) يدير مستخدمين، نسخ احتياطية،
// أو سجلات منشآت **تخص مستشفيات ثانية غيره تماماً**، رغم إن الفرونت إند لا
// يعرض له هذا إطلاقاً — نفس نمط الثغرة اللي أصلحناها سابقاً بالصلاحيات
// العامة (RBAC)، بس هذي المرة على مستوى المنشأة بدل الموديول.
//
// هذا الـ middleware يُستخدم للعمليات التي *يجب* أن تبقى حصراً للإدمن العام،
// بغض النظر عن أي منشأة (إدارة قائمة المنشآت نفسها، النسخ الاحتياطي الكامل
// للنظام، سجل التدقيق الشامل) — عمليات لا معنى لتفويضها لإدمن محلي واحد
// لأنها تلمس بيانات كل المنشآت دفعة وحدة بطبيعتها (مثل ملف نسخة احتياطية
// واحد يحوي بيانات كل المستشفيات مع بعض).
const requireGlobalAdmin = (req, res, next) => {
  if (req.user?.role !== 'admin' || req.user?.hospitalId) {
    return res.status(403).json({ message: 'هذي الصفحة للإدمن العام (مستوى الوزارة) فقط' });
  }
  next();
};

module.exports = requireGlobalAdmin;
