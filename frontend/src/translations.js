/**
 * دالة الترجمة — الاستخدام:
 *   import { useT } from '../translations';
 *   const tr = useT();
 *   <h1>{tr('doc_management')}</h1>
 *
 * تعتمد على AppContext React state بدلاً من localStorage مباشرة
 * لضمان إعادة الرسم الفوري عند تغيير اللغة
 */
/**
 * دالة الترجمة الصحيحة:
 * كل component يجب أن يأخذ lang من useApp() ثم يستدعي useT()
 * 
 * الاستخدام:
 *   const { lang } = useApp();
 *   const tr = useT(lang);
 *   <h1>{tr('doc_management')}</h1>
 *
 * سبب قبول lang كـ parameter: لضمان إعادة الرسم التلقائي
 * عند تغيير اللغة، لأن lang يأتي من React state في useApp
 */
export function useT(lang) {
  // إذا لم يُمرر lang، نحاول نقرأه من AppContext
  let resolvedLang = lang;
  if (!resolvedLang) {
    try {
      // eslint-disable-next-line react-hooks/rules-of-hooks
      const ctx = useContext(AppContext);
      resolvedLang = (ctx && ctx.lang) ? ctx.lang : (localStorage.getItem('lang') || 'ar');
    } catch {
      resolvedLang = localStorage.getItem('lang') || 'ar';
    }
  }

  return (key) => {
    if (!translations[key]) {
      console.warn(`[i18n] Missing key: "${key}"`);
      return key;
    }
    return translations[key][resolvedLang] || key;
  };
}

/**
 * للاستخدام خارج React (مثل constants)
 */
export function t(key, lang = 'ar') {
  if (!translations[key]) return key;
  return translations[key][lang] || key;
}

export default translations;
